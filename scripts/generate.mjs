// Generate the static entry and page catalog from providers.config.mjs.
//
// Magpie only sees exported functions, so the entry must stay static. This
// script keeps the config as the single place to add or remove a provider.

import { existsSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"
import providers from "../providers.config.mjs"

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const modules = [...new Set(providers.map((provider) => provider.module).filter(Boolean))]

// Keep each vendor's own artwork so one bundle does not repaint every row.
// A vendor that sets auth.icon in code still wins over this.
function packageIcon(module) {
  const file = join(root, module, "..", "package.json")
  if (!existsSync(file)) return undefined
  try {
    return JSON.parse(readFileSync(file, "utf8"))?.magpie?.icon
  } catch {
    return undefined
  }
}

const icons = new Map(modules.map((module) => [module, packageIcon(module)]))

const MIME = {
  ".png": "image/png",
  ".svg": "image/svg+xml",
  ".ico": "image/x-icon",
  ".webp": "image/webp",
}

// The entry runs inside Magpie, not in the page: embed the bytes so the icon
// never depends on a relative file path or a network request.
function embeddedIcon(icon) {
  if (typeof icon !== "string" || !icon) return undefined
  if (icon.startsWith("data:")) return icon
  const file = join(root, "page", icon)
  if (!existsSync(file)) return undefined
  const ext = icon.slice(icon.lastIndexOf(".")).toLowerCase()
  const mime = MIME[ext]
  if (!mime) return undefined
  return `data:${mime};base64,${readFileSync(file).toString("base64")}`
}

const monogramHues = {
  编程: [212, 78],
  办公: [154, 62],
  研发: [38, 70],
  国内: [12, 64],
  免费: [190, 62],
  聚合: [332, 56],
  工具: [262, 50],
}

function escapeXml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
}

function monogramIcon(provider) {
  const label = String(provider.mark || provider.label || provider.id || "?").slice(0, 2)
  const [hue, saturation] = monogramHues[provider.group] ?? [220, 45]
  const svg =
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32">` +
    `<rect width="32" height="32" rx="9" fill="hsl(${hue} 28% 13%)"/>` +
    `<rect x="1" y="1" width="30" height="30" rx="8" fill="none" stroke="hsl(${hue} ${saturation}% 55% / .28)"/>` +
    `<text x="16" y="20.5" text-anchor="middle" font-family="Segoe UI, sans-serif" font-size="${label.length > 1 ? 10 : 13}" font-weight="700" fill="hsl(${hue} ${saturation}% 74%)">${escapeXml(label)}</text>` +
    `</svg>`
  return `data:image/svg+xml,${encodeURIComponent(svg)}`
}

const lines = [
  "// Generated by scripts/generate.mjs from providers.config.mjs.",
  "// Do not edit by hand; edit the config and run `node scripts/generate.mjs`.",
  "",
  'import { defineProvider } from "./runtime/safe.mjs"',
  "",
]

// Vendors are imported lazily, inside the provider's own try/catch. A vendor
// whose top-level code throws then loses only itself, not the whole bundle.

for (const provider of providers) {
  if (!provider.module || !provider.export) {
    throw new Error(`${provider.id}: module and export are required`)
  }
  const spec = {
    id: provider.id,
    label: provider.label,
    kind: provider.kind ?? "provider",
    export: provider.export,
    icon:
      embeddedIcon(provider.icon) ??
      icons.get(provider.module) ??
      monogramIcon(provider),
    loadTimeoutMs: provider.loadTimeoutMs,
    usageTimeoutMs: provider.usageTimeoutMs,
    checkinTimeoutMs: provider.checkinTimeoutMs,
    modelsTimeoutMs: provider.modelsTimeoutMs,
  }
  lines.push(
    `export const ${provider.export} = defineProvider(${JSON.stringify(spec)}, () => import(${JSON.stringify(provider.module)}).then((mod) => mod.${provider.export}))`,
  )
}

writeFileSync(join(root, "index.mjs"), lines.join("\n") + "\n", "utf8")

const catalog = providers.map((provider) => ({
  id: provider.id,
  label: provider.label,
  mark: provider.mark ?? "",
  group: provider.group,
  order: provider.order,
  kind: provider.kind ?? "provider",
  icon: provider.icon,
  options: provider.options,
  usage: provider.usage !== false,
  checkin: provider.checkin !== false,
  login: Array.isArray(provider.login) ? [...new Set(provider.login)] : [],
  baseUrl: provider.baseUrl,
  protocol: provider.protocol,
  defaultModel: provider.defaultModel,
}))

writeFileSync(
  join(root, "page", "catalog.js"),
  `window.__PROVIDER_BUNDLE_CATALOG__ = ${JSON.stringify(catalog, null, 2)};\n`,
  "utf8",
)

const snapshot = join(root, "page", "snapshot.js")
if (!existsSync(snapshot)) {
  writeFileSync(
    snapshot,
    'window.__PROVIDER_BUNDLE_SNAPSHOT__ = {"at":"","providers":{}};\n',
    "utf8",
  )
}

console.log(
  JSON.stringify({
    ok: true,
    providers: providers.filter((provider) => provider.kind !== "tools").length,
    tools: providers.filter((provider) => provider.kind === "tools").length,
  }),
)
